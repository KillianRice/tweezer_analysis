function funcOut = TOF_Temperature_AvgDatasets(analyVar, indivDataset, avgDataset)
    
    %% TOF with avg datasets - SKK 2025.04.08
    % Fits TOF function to the cloud Radius to indivDataset and avgDataset
    function v = form(coeffs,x) 
        kB = 1.38E-23; % Boltzmanns constant
        sigma_0 = coeffs(1); % Initial Cloud Radius
        T = coeffs(2); % Temperature fit value
        v = sqrt(coeffs(1).^2+(analyVar.kBoltz*coeffs(2)/analyVar.mass)*x.^2);%input radii are in um so I..
    end
    
    indVarField = 'imagevcoAtom'; % independent variable
    depVarField1 = 'cloudRadX'; % dependent variable
    depVarField2 = 'cloudRadY'; % dependent variable
    
    %% initial guess code
    function initialguess = x0(xdata, ydata)
        initialguess = [1,1]
        initialguess(2) = 1e-3;
        initialguess(1) = mean(ydata);
    end
    %% options
    % the base_fit function is designed to be flexible, and can accept a
    % lot of different parameters to adjust 
    %%%%% Default Options %%%%%
%         options = struct(...
%         'DataPlotFunction', @defaultDataPlot,...
%         'AvgDataPlotFunction', @defaultAvgDataPlot,...
%         'FitLinePlotFunction', @defaultFitLinePlot,...
%         'AnnotateFunction', @defaultAnnotate,...
%         'IndivFitPlotFunction', @defaultIndivFitPlot,...
%         'PlotIndivFits' , true,...
%         'PlotAvgFits', true,...
%         'XAxisLabel', indVarField ,...
%         'YAxisLabel', depVarField,...
%         'FitLB', [],...
%         'FitUB', [],...
%         'FitOptions', struct('Display','off'),...
%         'PlotInitialGuess', true, ...
%         'InitialGuessPlotFunction', @defaultInitialGuessPlot,...
%         'PlotAll', true,...
%         'PlotAllAvgs', true, ...
%         'CoeffNames', {{}},...
%         'CoeffUnits', {{}},...
%         'YAxisScale', 'linear',...
%         'XAxisScale', 'linear');
    %%%%%%%%%%%%%%%%%%%%%%%%%%%
    options = struct(...
        'PlotIndivFits', false,...
        'PlotAll', false,...
        'PlotAllAvgs', true,...
        'CoeffNames', {{'\sigma_0', 'T'}},...
        'CoeffUnits', {{'um','mK'}},...
        'AnnotateFunction', @myAnnotate,...
        'PlotInitialGuess', true);
    
    base_fit(analyVar, indivDataset, avgDataset, @form, indVarField, depVarField1, @x0, options)
    base_fit(analyVar, indivDataset, avgDataset, @form, indVarField, depVarField2, @x0, options)

    funcOut.analyVar = analyVar;
    funcOut.indivDataset = indivDataset;
    funcOut.avgDataset = avgDataset;
end

function an = myAnnotate(coeffs, err, coeffNames, coeffUnits)
    dim = [.15 .6 .3 .3];
     strs{1} = [coeffNames{1}, ': ', num2str(coeffs(1)),' ', coeffUnits{1},newline];
     strs{2} = [coeffNames{2}, ': ', num2str(coeffs(2)*10^(-3)),' ', coeffUnits{2}];
    an = annotation('textbox', dim, 'String', strjoin(strs),...
        'FitBoxToText', 'on', 'BackgroundColor', 'white');
end
