function funcOut = SFI_fit_and_exctract(analyVar,indivDataset,avgDataset)
    form = @(coeffs,x) coeffs(1) * exp(-(x-coeffs(2)).^2 ./ (2*coeffs(3)^2))+ coeffs(4) * exp(-(x-coeffs(5)).^2 ./ (2*coeffs(6)^2)) + coeffs(7);
    Gaussianform = @(coeffs,x) coeffs(1) * exp(-(x-coeffs(2)).^2 ./ (2*coeffs(3)^2)) + coeffs(4);
    
    %% Initial Guesses for the functional forms obove.
    function x0 = initial_guess(x, y)
        x0 = zeros(7,1);
        x0(1) = max(y);
        x0(2) = 6*10^(-6);
        x0(3) = sqrt(sum((x-x0(2)).^2.*y)/sum(y));
        x0(4) = max(y)/5;
        x0(5) = x0(2) + 1*10^(-6);
        x0(6) = 10^(-6);
        x0(7) = min(y);
    end
    function x0 = initial_guess_Gaussianform(x, y)
        x0 = zeros(4,1);
        x0(1) = max(y);
        x0(2) = sum(x.*y)/sum(y);
        x0(3) = sqrt(sum((x-x0(2)).^2.*y)/sum(y));
        x0(4) = min(y);
    end

    totsfi_overfiles = zeros(size(indivDataset{1}.mcsSpectra{1}(:,1:end)));
    for i= 1:analyVar.numBasenamesAtom % loop over batches
        indivDataset{i}.SFI_fit_1 = zeros(indivDataset{i}.CounterMCS,1); % counts the number of MCS files and initialized a 0-vector
        indivDataset{i}.SFI_fit_2 = zeros(indivDataset{i}.CounterMCS,1); % counts the number of MCS files and initialized a 0-vector
        indivDataset{i}.CumSFI_fit_1 = zeros(indivDataset{i}.CounterMCS,1); % counts the number of MCS files and initialized a 0-vector
        indivDataset{i}.CumSFI_fit_2 = zeros(indivDataset{i}.CounterMCS,1); % counts the number of MCS files and initialized a 0-vector
        totsfi = zeros(size(indivDataset{i}.mcsSpectra{1}(:,1:end)));
        %%%% Fitting each MCS spectra at a time.
        for j = 1:indivDataset{i}.CounterMCS % loop over all the MCS files
            x = indivDataset{i}.mcsSpectra{j}(:,1);
            y = indivDataset{i}.mcsSpectra{j}(:,2);
            initguess = initial_guess(x,y);
            % fitting the mcs file(SFI)
            % coeffs{j}=lsqcurvefit(form,initguess,x,y,[],[],struct('Display','off'));
            % indivDataset{i}.SFI_fit_1(j,1) = coeffs{j}(1)*sqrt(2*pi)*coeffs{j}(3);
            % indivDataset{i}.SFI_fit_2(j,1) = coeffs{j}(4)*sqrt(2*pi)*coeffs{j}(6);
            % plotting to check the fit
            % fitx = linspace(min(x),max(x),1000);

            % figure 
            % hold on
            % plot(x,y,...
            %      'LineStyle','-',...
            %      'MarkerSize', analyVar.markerSize,...
            %      'MarkerFaceColor', analyVar.COLORS(i,:),...
            %      'Color', analyVar.COLORS(i,:));
            % plot(fitx,form(coeffs{i},fitx),...
            %      'LineStyle','-',...
            %      'MarkerSize', analyVar.markerSize,...
            %      'MarkerFaceColor', analyVar.COLORS(i,:),...
            %      'Color', analyVar.COLORS(i,:));
            % xlabel('Time(sec)')
            % ylabel('Bin counts')
            % plot(fitx,form(initguess,fitx),...
            %      'LineStyle','--',...
            %      'MarkerSize', analyVar.markerSize,...
            %      'MarkerFaceColor', analyVar.COLORS(i,:),...
            %      'Color', analyVar.COLORS(i,:));
            % hold off
            totsfi = totsfi + indivDataset{i}.mcsSpectra{j}(:,1:end);
        end
      
        y = totsfi(:,2);
        initguess = initial_guess(x,y);
        % coeffs_cumSFI=lsqcurvefit(form,initguess,x,y,[],[],struct('Display','off')); % Fitting the cumulative SFI
        % indivDataset{i}.CumSFI_fit_1(j,1) = coeffs_cumSFI(1)*sqrt(2*pi)*coeffs_cumSFI(3);
        % indivDataset{i}.SFI_fit_2(j,1) = coeffs_cumSFI(4)*sqrt(2*pi)*coeffs_cumSFI(6);
        % % plotting to check the fit
        fitx = linspace(min(x),max(x),1000);

        % figure 
        % hold on
        % plot(x,y,...
        %      'LineStyle','-',...
        %      'MarkerSize', analyVar.markerSize,...
        %      'MarkerFaceColor', analyVar.COLORS(i,:),...
        %      'Color', analyVar.COLORS(i,:));
        % plot(fitx,form(coeffs_cumSFI,fitx),...
        %      'LineStyle','-',...
        %      'MarkerSize', analyVar.markerSize,...
        %      'MarkerFaceColor', analyVar.COLORS(i+1,:),...
        %      'Color', analyVar.COLORS(i+1,:));
        % xlabel('Time(sec)')
        % ylabel('Bin counts')
        % title(['File',num2str(i)])
        % plot(fitx,form(initguess,fitx),...
        %      'LineStyle','--',...
        %      'MarkerSize', analyVar.markerSize,...
        %      'MarkerFaceColor', analyVar.COLORS(i,:),...
        %      'Color', analyVar.COLORS(i,:));
        hold off
        totsfi_overfiles = totsfi_overfiles + totsfi(:,2);
    end
        y = totsfi_overfiles(:,2);
        initguess = initial_guess_Gaussianform(x,y);
        coeffs_cumSFI=lsqcurvefit(Gaussianform,initguess,x,y,[],[],struct('Display','off')); % Fitting the cumulative SFI
       
        %plotting to check the fit
        fitx = linspace(min(x),max(x),1000);

        figure 
        hold on
        plot(x,y,...
             'LineStyle','-',...
             'MarkerSize', analyVar.markerSize,...
             'MarkerFaceColor', analyVar.COLORS(1,:),...
             'Color', analyVar.COLORS(1,:),...
             'DisplayName','Cum SFI Data');
        plot(fitx,Gaussianform(coeffs_cumSFI,fitx),...
             'LineStyle','--',...
             'MarkerSize', analyVar.markerSize,...
             'MarkerFaceColor', analyVar.COLORS(1,:),...
             'Color', analyVar.COLORS(1,:),...
             'DisplayName','Fit');
        xlabel('Time(sec)')
        ylabel('Bin counts')
        title(['Cum. SFI over all files',' Center = ', num2str(coeffs_cumSFI(2)*10^6),' us']);
        subtitle(['FWHM = ',num2str(coeffs_cumSFI(3)*10^6*2*sqrt(2*log(2))), ' us']);
        plot(fitx,Gaussianform(initguess,fitx),...
             'LineStyle',':',...
             'MarkerSize', analyVar.markerSize,...
             'MarkerFaceColor', analyVar.COLORS(1,:),...
             'Color', analyVar.COLORS(1,:),...
             'DisplayName','Initial Guess');
        legend();
        hold off


        y = totsfi_overfiles(:,2);
        initguess = initial_guess(x,y);
        coeffs_cumSFI=lsqcurvefit(form,initguess,x,y,[],[],struct('Display','off')); % Fitting the cumulative SFI
       
        %plotting to check the fit
        fitx = linspace(min(x),max(x),1000);

        figure 
        hold on
        plot(x,y,...
             'LineStyle','-',...
             'MarkerSize', analyVar.markerSize,...
             'MarkerFaceColor', analyVar.COLORS(1,:),...
             'Color', analyVar.COLORS(1,:),...
             'DisplayName','Cum SFI Data');
        plot(fitx,form(coeffs_cumSFI,fitx),...
             'LineStyle','--',...
             'MarkerSize', analyVar.markerSize,...
             'MarkerFaceColor', analyVar.COLORS(1,:),...
             'Color', analyVar.COLORS(1,:),...
             'DisplayName','Fit');
        xlabel('Time(sec)')
        ylabel('Bin counts')
        title(['Cum. SFI over all files',' Center = ', num2str(coeffs_cumSFI(2)*10^6),' us']);
        subtitle(['FWHM1 = ',num2str(coeffs_cumSFI(3)*10^6*2*sqrt(2*log(2))), ' us',...
            ' FWHM2 = ', num2str(abs(coeffs_cumSFI(6)*10^6*2*sqrt(2*log(2)))), ' us']);
        plot(fitx,form(initguess,fitx),...
             'LineStyle',':',...
             'MarkerSize', analyVar.markerSize,...
             'MarkerFaceColor', analyVar.COLORS(1,:),...
             'Color', analyVar.COLORS(1,:),...
             'DisplayName','Initial Guess');
        legend();
        hold off
    funcOut.analyVar = analyVar;
    funcOut.indivDataset= indivDataset;
    funcOut.avgDataset= avgDataset;
end