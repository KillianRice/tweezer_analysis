function an = myAnnotate(coeffs, err, coeffNames, coeffUnits)

    dim = [.6 .5 .3 .3];

    % ---------------------------------------------------------
    % Convert sigma -> FWHM
    % ---------------------------------------------------------

    fwhmFactor = 2*sqrt(2*log(2));

    coeffs(3) = coeffs(3) * fwhmFactor;
    coeffs(6) = coeffs(6) * fwhmFactor;
    coeffs(9) = coeffs(9) * fwhmFactor;

    err(3) = err(3) * fwhmFactor;
    err(6) = err(6) * fwhmFactor;
    err(9) = err(9) * fwhmFactor;

    % ---------------------------------------------------------
    % Trap frequencies
    %
    % Line position is in MHz.
    % Divide by 2, then convert MHz -> Hz.
    % ---------------------------------------------------------

    trapFrequency1 = coeffs(2) / 2 * 1e6;
    trapFrequency2 = coeffs(5) / 2 * 1e6;
    trapFrequency3 = coeffs(8) / 2 * 1e6;

    trapFrequency1_err = err(2) / 2 * 1e6;
    trapFrequency2_err = err(5) / 2 * 1e6;
    trapFrequency3_err = err(8) / 2 * 1e6;

    % ---------------------------------------------------------
    % Default names/units
    % ---------------------------------------------------------

    if isempty(coeffNames)
        coeffNames = cell(1,numel(coeffs));

        for i = 1:numel(coeffs)
            coeffNames{i} = ['Coeff ', num2str(i)];
        end
    end

    if isempty(coeffUnits)
        coeffUnits = cell(1,numel(coeffs));

        for i = 1:numel(coeffs)
            coeffUnits{i} = '';
        end
    end

    % ---------------------------------------------------------
    % Build annotation
    % ---------------------------------------------------------

    strs = cell(numel(coeffs)+3,1);

    for i = 1:numel(coeffs)

        strs{i} = [ ...
            char(coeffNames{i}), ': ', ...
            char(unc_string(coeffs(i),err(i))), ...
            ' ', ...
            char(coeffUnits{i})];

    end

    % ---------------------------------------------------------
    % Add trap frequencies
    % ---------------------------------------------------------

    strs{numel(coeffs)+1} = [ ...
        'Trap frequency 1: ', ...
        char(unc_string(trapFrequency1,trapFrequency1_err)), ...
        ' Hz'];

    strs{numel(coeffs)+2} = [ ...
        'Trap frequency 2: ', ...
        char(unc_string(trapFrequency2,trapFrequency2_err)), ...
        ' Hz'];

    strs{numel(coeffs)+3} = [ ...
        'Trap frequency 3: ', ...
        char(unc_string(trapFrequency3,trapFrequency3_err)), ...
        ' Hz'];

    % ---------------------------------------------------------
    % Create annotation
    % ---------------------------------------------------------

    an = annotation('textbox', dim, ...
        'String', strjoin(strs, newline), ...
        'FitBoxToText', 'on', ...
        'BackgroundColor', 'white');

end

