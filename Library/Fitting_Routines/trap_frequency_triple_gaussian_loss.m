function funcOut = trap_frequency_triple_gaussian_loss(analyVar, indivDataset, avgDataset)

    % Three independent Gaussian loss features.
    %
    % coeffs =
    % [Amplitude 1, Line Center 1, FWHM 1, ...
    %  Amplitude 2, Line Center 2, FWHM 2, ...
    %  Amplitude 3, Line Center 3, FWHM 3, Offset]
    %
    % The three Gaussian positions and widths are completely
    % independent from one another.

    form = @(coeffs,x) ...
        coeffs(10) ...
        - coeffs(1) * exp(-(x-coeffs(2)).^2 ./ (2*coeffs(3)^2)) ...
        - coeffs(4) * exp(-(x-coeffs(5)).^2 ./ (2*coeffs(6)^2)) ...
        - coeffs(7) * exp(-(x-coeffs(8)).^2 ./ (2*coeffs(9)^2));

    indVarField = 'imagevcoAtom';
    % depVarField = 'sfiIntegral_roi1';
    % depVarField = 'sfiIntegral';
    depVarField = 'winTotNum';
   

    function x0 = initial_guess(x, y)

        x0 = zeros(10,1);

        % ---------------------------------------------------------
        % Initial guesses
        % ---------------------------------------------------------

        % Approximate background
        offset = max(y);

        % Approximate center of the three-feature spectrum
        %centerGuess = sum(x.*y)/sum(y);
        %centerGuess = 0.00017;
        % Initial positions
        position1 = 0.000080;%centerGuess - 0.00015;
        position2 = 0.000141;%centerGuess;
        position3 = 0.0007;%centerGuess + 0.00038;

        % Initial widths (sigma)
        sigma1 = 0.000008;
        sigma2 = 0.000008;
        sigma3 = 0.00008;

        % Estimate amplitudes from the data
        amp1 =abs(max(y));
        amp2 = abs(max(y));
        amp3 =abs(max(y));

        % ---------------------------------------------------------
        % Coefficient vector
        %
        % [A1, x1, sigma1, ...
        %  A2, x2, sigma2, ...
        %  A3, x3, sigma3, offset]
        % ---------------------------------------------------------

        x0(1) = amp1;
        x0(2) = position1;
        x0(3) = sigma1;

        x0(4) = amp2;
        x0(5) = position2;
        x0(6) = sigma2;

        x0(7) = amp3;
        x0(8) = position3;
        x0(9) = sigma3;

        x0(10) = offset;

    end

    %% options
    % the base_fit function is designed to be flexible, and can accept a
    % lot of different parameters to adjust 
    %%%%% Default Options %%%%%
%     options = struct(...
%         'DataPlotFunction', @defaultDataPlot,...
%         'AvgDataPlotFunction', @defaultAvgDataPlot,...
%         'FitLinePlotFunction', @defaultFitLinePlot,...
%         'AnnotateFunction', @defaultAnnotate,...
%         'IndivFitPlotFunction', @defaultIndivFitPlot,...
%         'PlotIndivFits' , true,...
%         'PlotAvgFits', true,...
%         'XAxisLabel', indVarField ,...
%         'YAxisLabel', depVarField,...
%         'FitLB', [],...
%         'FitUB', [],...
%         'FitOptions', struct('Display','off'),...
%         'PlotInitialGuess', true, ...
%         'InitialGuessPlotFunction', @defaultInitialGuessPlot,...
%         'PlotAll', true,...
%         'PlotAllAvgs', true, ...
%         'CoeffNames', {{}},...
%         'CoeffUnits', {{}},...
%         'YAxisScale', 'linear',...
%         'XAxisScale', 'linear');

    options = struct(...
        'PlotIndivFits', false,...
        'PlotAll', false,...
        'PlotAllAvgs', true,...
        'PlotInitialGuess', true,...
        'XAxisLabel', 'ODT Modulation Frequency (MHz)',...
        'YAxisLabel', 'Atom Number' ,...
        'CoeffNames', {{ ...
            'Amplitude 1', ...
            'Line Center 1', ...
            'FWHM 1', ...
            'Amplitude 2', ...
            'Line Center 2', ...
            'FWHM 2', ...
            'Amplitude 3', ...
            'Line Center 3', ...
            'FWHM 3', ...
            'Offset'}},...
        'CoeffUnits', {{ ...
            '', ...
            'MHz', ...
            'MHz', ...
            '', ...
            'MHz', ...
            'MHz', ...
            '', ...
            'MHz', ...
            'MHz', ...
            ''}},...
        'AnnotateFunction', @myAnnotate,...
        'Statistics', 'gaussian');
    
    base_fit(analyVar, indivDataset, avgDataset, ...
        form, indVarField, depVarField, @initial_guess, options)


    funcOut.analyVar = analyVar;
    funcOut.indivDataset = indivDataset;
    funcOut.avgDataset = avgDataset;

end


