function questions = get_odt_questions()
%GET_ODT_QUESTIONS Add ODT-specific prompts here later.
%
% Example:
%
% questions = [ ...
%     make_text_question( ...
%         'ODT Loading Time', ...
%         'ODT Loading Time', ...
%         'time units')
%
%     make_calibrated_question( ...
%         'ODT Power', ...
%         'ODT Power control voltage', ...
%         'V', ...
%         'W', ...
%         @(voltage) calibration_expression, ...
%         'Power [W] = ...') ...
%     ];

    questions = struct( ...
        'Parameter',{}, ...
        'Prompt',{}, ...
        'EnteredUnits',{}, ...
        'CalibratedUnits',{}, ...
        'IsCalibrated',{}, ...
        'CalibrationFunction',{}, ...
        'CalibrationDescription',{});

end


function question = make_text_question(parameter,prompt,enteredUnits)
%MAKE_TEXT_QUESTION Construct a non-calibrated question.

    question = struct( ...
        'Parameter',string(parameter), ...
        'Prompt',string(prompt), ...
        'EnteredUnits',string(enteredUnits), ...
        'CalibratedUnits',"", ...
        'IsCalibrated',false, ...
        'CalibrationFunction',[], ...
        'CalibrationDescription',"None");

end


function question = make_calibrated_question( ...
    parameter, ...
    prompt, ...
    enteredUnits, ...
    calibratedUnits, ...
    calibrationFunction, ...
    calibrationDescription)
%MAKE_CALIBRATED_QUESTION Construct a calibrated question.

    question = struct( ...
        'Parameter',string(parameter), ...
        'Prompt',string(prompt), ...
        'EnteredUnits',string(enteredUnits), ...
        'CalibratedUnits',string(calibratedUnits), ...
        'IsCalibrated',true, ...
        'CalibrationFunction',calibrationFunction, ...
        'CalibrationDescription',string(calibrationDescription));

end


function promptText = format_unit_prompt(unitsText)
%FORMAT_UNIT_PROMPT Add units to a command-window prompt.

    if strlength(unitsText) == 0
        promptText = '';
    else
        promptText = sprintf(' [%s]',unitsText);
    end

end


function tf = is_na_response(response)
%IS_NA_RESPONSE Recognize common N/A responses.

    normalizedResponse = lower(strtrim(response));

    tf = any(strcmp(normalizedResponse,{ ...
        'n/a', ...
        'na', ...
        'not applicable', ...
        'not available'}));

end


function numericValue = extract_numeric_value(response)
%EXTRACT_NUMERIC_VALUE Extract the first numeric value from a response.
%
% Examples:
%   '2'       -> 2
%   '2 V'     -> 2
%   '-1.5V'   -> -1.5
%   '3.2e-4'  -> 3.2e-4

    numberToken = regexp( ...
        response, ...
        '[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?', ...
        'match', ...
        'once');

    if isempty(numberToken)
        numericValue = NaN;
    else
        numericValue = str2double(numberToken);
    end

end