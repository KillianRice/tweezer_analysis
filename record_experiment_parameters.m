function experimentTable = record_experiment_parameters(outputDir)
%RECORD_EXPERIMENT_PARAMETERS Interactively record experimental settings.
%
%   experimentTable = record_experiment_parameters
%   experimentTable = record_experiment_parameters(outputDir)
%
% The function:
%   1. Prompts for the experiment type.
%   2. Asks experiment-specific questions.
%   3. Accepts "n/a" for every prompt.
%   4. Applies calibrations where required.
%   5. Displays the results as a MATLAB table.
%   6. Saves timestamped CSV and MAT files.
%
% Current experiment types:
%   - Tweezer
%   - ODT
%
% Add future ODT prompts in get_odt_questions().
%
% Calibrations currently implemented:
%   689 Cooling Power:
%       calibrated power [uW] = 0.2355*[V] + 0.0187
%
%   Tweezer Power:
%       calibrated power [mW] = 1.6*[V]
%
% For calibrated prompts, enter only the control voltage, for example:
%       2
%       2 V
%       n/a
%
% The table stores both the entered value and the calibrated value.

    %% Output directory

    if nargin < 1 || isempty(outputDir)
        outputDir = pwd;
    end

    if ~exist(outputDir,'dir')
        mkdir(outputDir);
    end

    %% Choose experiment type

    experimentChoices = {'Tweezer','ODT'};

    fprintf('\nExperimental Parameter Recorder\n');
    fprintf('-------------------------------\n');
    fprintf('Choose experiment type:\n');

    for choiceIndex = 1:numel(experimentChoices)
        fprintf('  %d. %s\n',choiceIndex,experimentChoices{choiceIndex});
    end

    experimentChoice = input( ...
        sprintf('Selection [1-%d]: ',numel(experimentChoices)), ...
        's');

    experimentNumber = str2double(strtrim(experimentChoice));

    if ~isscalar(experimentNumber) || ...
            ~isfinite(experimentNumber) || ...
            experimentNumber ~= round(experimentNumber) || ...
            experimentNumber < 1 || ...
            experimentNumber > numel(experimentChoices)

        error('Invalid experiment-type selection.');
    end

    experimentType = experimentChoices{experimentNumber};

    %% Get experiment-specific questions

    switch lower(experimentType)

        case 'tweezer'
            questions = get_tweezer_questions();

        case 'odt'
            questions = get_odt_questions();

        otherwise
            error('Unsupported experiment type: %s',experimentType);
    end

    %% Handle an empty question set

    if isempty(questions)

        warning(['No questions are currently defined for experiment type ' ...
                 '"%s". Add them in get_odt_questions().'],experimentType);

        experimentTable = table;
        return;
    end

    %% Ask all questions

    numQuestions = numel(questions);

    experimentColumn = strings(numQuestions,1);
    parameterColumn = strings(numQuestions,1);
    enteredValueColumn = strings(numQuestions,1);
    enteredUnitsColumn = strings(numQuestions,1);
    calibratedValueColumn = nan(numQuestions,1);
    calibratedUnitsColumn = strings(numQuestions,1);
    calibrationColumn = strings(numQuestions,1);
    notesColumn = strings(numQuestions,1);

    fprintf('\nRecording %s experimental parameters.\n',experimentType);
    fprintf('Enter "n/a" for any unavailable or inapplicable value.\n\n');

    for questionIndex = 1:numQuestions

        question = questions(questionIndex);

        experimentColumn(questionIndex) = experimentType;
        parameterColumn(questionIndex) = question.Parameter;
        enteredUnitsColumn(questionIndex) = question.EnteredUnits;
        calibratedUnitsColumn(questionIndex) = question.CalibratedUnits;
        calibrationColumn(questionIndex) = question.CalibrationDescription;

        response = input( ...
            sprintf('%s%s: ', ...
                question.Prompt, ...
                format_unit_prompt(question.EnteredUnits)), ...
            's');

        response = strtrim(response);

        if isempty(response)
            response = 'n/a';
        end

        enteredValueColumn(questionIndex) = response;

        if is_na_response(response)

            calibratedValueColumn(questionIndex) = NaN;
            notesColumn(questionIndex) = "n/a";
            continue;
        end

        if question.IsCalibrated

            numericValue = extract_numeric_value(response);

            if isnan(numericValue)

                warning(['Could not extract a numeric value from "%s". ' ...
                         'Calibration was not applied.'],response);

                calibratedValueColumn(questionIndex) = NaN;
                notesColumn(questionIndex) = ...
                    "Calibration not applied: numeric value not recognized.";

            else

                calibratedValueColumn(questionIndex) = ...
                    question.CalibrationFunction(numericValue);

                notesColumn(questionIndex) = ...
                    sprintf('Calculated from entered value %.12g %s.', ...
                        numericValue,question.EnteredUnits);
            end

        else

            calibratedValueColumn(questionIndex) = NaN;
            notesColumn(questionIndex) = "";
        end
    end

    %% Add metadata columns

    timestamp = datetime('now');
    timestampColumn = repmat(timestamp,numQuestions,1);

    %% Construct output table

    experimentTable = table( ...
        timestampColumn, ...
        experimentColumn, ...
        parameterColumn, ...
        enteredValueColumn, ...
        enteredUnitsColumn, ...
        calibratedValueColumn, ...
        calibratedUnitsColumn, ...
        calibrationColumn, ...
        notesColumn, ...
        'VariableNames',{ ...
            'Timestamp', ...
            'ExperimentType', ...
            'Parameter', ...
            'EnteredValue', ...
            'EnteredUnits', ...
            'CalibratedValue', ...
            'CalibratedUnits', ...
            'Calibration', ...
            'Notes'});

    %% Display table

    fprintf('\nRecorded Experimental Parameters\n');
    fprintf('--------------------------------\n');
    disp(experimentTable);

    %% Save files

    timestampText = datestr(timestamp,'yyyy-mm-dd_HHMMSS');
    safeExperimentType = regexprep(experimentType,'[^a-zA-Z0-9_-]','_');

    baseFilename = sprintf( ...
        '%s_ExperimentParameters_%s', ...
        safeExperimentType, ...
        timestampText);

    csvFile = fullfile(outputDir,[baseFilename '.csv']);
    matFile = fullfile(outputDir,[baseFilename '.mat']);

    writetable(experimentTable,csvFile);
    save(matFile,'experimentTable','experimentType','timestamp');

    fprintf('\nSaved experiment notes to:\n');
    fprintf('  %s\n',csvFile);
    fprintf('  %s\n\n',matFile);

end


